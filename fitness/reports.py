"""PDF client report, ported from the FPDF export in ACEest v3.1.2 / v3.2.4."""

from fpdf import FPDF

CLIENT_FIELDS = [
    ("name", "Name"), ("age", "Age"), ("height", "Height (cm)"), ("weight", "Weight (kg)"),
    ("program", "Program"), ("calories", "Calories (kcal/day)"), ("target_weight", "Target weight"),
    ("target_adherence", "Target adherence (%)"), ("generated_plan", "Generated plan"),
    ("membership_status", "Membership"), ("membership_end", "Membership end"),
]


def _latin1(value):
    # The built-in PDF fonts only cover Latin-1; replace anything else instead of failing.
    text = "-" if value is None or value == "" else str(value)
    return text.encode("latin-1", "replace").decode("latin-1")


def build_client_report(client, progress, workouts, metrics, version="unknown"):
    """Return the PDF bytes for one client. Arguments are plain dicts / lists of dicts."""
    pdf = FPDF()
    pdf.set_title(_latin1(f"ACEest Client Report - {client['name']}"))
    pdf.add_page()

    def line(text, style="", size=11):
        pdf.set_font("Helvetica", style, size)
        pdf.multi_cell(0, 7, _latin1(text), new_x="LMARGIN", new_y="NEXT")

    def heading(text):
        pdf.ln(3)
        line(text, "B", 13)

    line(f"ACEest Client Report - {client['name']}", "B", 16)
    line(f"Generated by ACEest Fitness & Gym v{version}", size=9)

    heading("Profile")
    for key, label in CLIENT_FIELDS:
        line(f"{label}: {_latin1(client.get(key))}")

    heading("Weekly adherence")
    if progress:
        for row in progress:
            line(f"{row['week']}: {row['adherence']}%")
        average = sum(r["adherence"] for r in progress) / len(progress)
        line(f"Average: {average:.1f}%", "B")
    else:
        line("No progress logged yet.")

    heading("Workouts")
    for row in workouts or []:
        line(f"{row['date']}  {row['workout_type']}  {row['duration_min']} min  {_latin1(row.get('notes'))}")
    if not workouts:
        line("No workouts logged yet.")

    heading("Body metrics")
    for row in metrics or []:
        line(f"{row['date']}  weight {row['weight']} kg  waist {_latin1(row.get('waist'))}  "
             f"body fat {_latin1(row.get('bodyfat'))}%")
    if not metrics:
        line("No metrics logged yet.")

    return bytes(pdf.output())
